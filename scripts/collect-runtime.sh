#!/bin/sh
# Assemble the final scratch filesystem inside the runtime-dependencies stage.
set -eu
variant=$1
root=/runtime
mkdir -p "$root/usr/local/bin" "$root/usr/lib" "$root/usr/share" \
    "$root/etc/ssl/certs" "$root/root" "$root/tmp" "$root/workspace"
mkdir -p "$root/usr/lib64"
ln -s usr/lib "$root/lib"
ln -s usr/lib64 "$root/lib64"
chmod 1777 "$root/tmp"
cp -a /opt/arturo/. "$root/usr/local/bin/"

copy_libraries() {
    # Include the interpreter as well as dependencies resolved by the loader.
    ldd "$1" > /tmp/arturo-ldd.txt
    if grep -q 'not found' /tmp/arturo-ldd.txt; then
        cat /tmp/arturo-ldd.txt >&2
        exit 1
    fi
    awk '{for (i=1;i<=NF;i++) if ($i ~ /^\//) print $i}' /tmp/arturo-ldd.txt |
        while IFS= read -r library; do
            cp -L --parents "$library" "$root"
        done
}

if [ "$variant" = mini ]; then
    copy_libraries /opt/arturo/arturo
    # Arturo loads regex and TLS libraries dynamically, so ldd alone is not
    # sufficient. Keep their SONAME files and each library's loader dependencies.
    for library in /usr/lib/*/libpcre2-8.so.* /usr/lib/*/libssl.so.* /usr/lib/*/libcrypto.so.*; do
        [ -f "$library" ] || continue
        cp -L --parents "$library" "$root"
        copy_libraries "$library"
    done
else
    # WebKit loads plugins and helper processes dynamically. Preserve its
    # installed library/data tree, including caches generated by package hooks.
    cp -a /usr/lib/. "$root/usr/lib/"
    cp -a /usr/share/. "$root/usr/share/"
    copy_libraries /opt/arturo/arturo
    for directory in /etc/fonts /etc/gtk-3.0 /etc/glvnd /etc/alternatives; do
        [ ! -d "$directory" ] || cp -a --parents "$directory" "$root"
    done
    # WebKit's sandbox invokes these helpers, which are not shell commands.
    for helper in /usr/bin/bwrap /usr/bin/xdg-dbus-proxy; do
        [ ! -f "$helper" ] || cp -a --parents "$helper" "$root"
    done
    # Keep runtime data and copyright notices, not manuals, translated messages,
    # package-manager data or installation machinery.
    rm -rf "$root/usr/share/man" "$root/usr/share/locale" \
        "$root/usr/share/lintian" "$root/usr/share/apt" \
        "$root/usr/share/dpkg" "$root/usr/lib/apt" "$root/usr/lib/dpkg"
    find "$root/usr/share/doc" -type f ! -name copyright -delete
    find "$root/usr/share/doc" -type l -delete
fi
# Preserve package licenses in mini too, without copying the documentation tree.
for copyright in /usr/share/doc/*/copyright; do
    [ ! -f "$copyright" ] || cp -L --parents "$copyright" "$root"
done
cp /etc/ssl/certs/ca-certificates.crt "$root/etc/ssl/certs/"
for config in /etc/nsswitch.conf /etc/ld.so.cache /etc/localtime; do
    [ ! -e "$config" ] || cp -L "$config" "$root/etc/"
done
printf 'root:x:0:0:root:/root:/sbin/nologin\n' > "$root/etc/passwd"
printf 'root:x:0:\n' > "$root/etc/group"
# CI logs show the actual filesystem contributors rather than guessed savings.
du -h -d 2 "$root" | sort -h
